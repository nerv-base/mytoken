// parseKind maps --kind onto the config's kind vocabulary.
func parseKind(v string) (instance.Kind, error) {
	k := instance.Kind(strings.TrimSpace(v))
	switch k {
	case instance.KindInstance, instance.KindBackupCopy:
		return k, nil
	}
	return "", fmt.Errorf("invalid --kind %q (want instance or backup-copy)", v)
}

// checkRoots rejects a config that would be stored broken. A disabled entry or
// a backup-copy keeps its roots verbatim: archived data need not exist, and the
// resolution rules never stat those roots.
func checkRoots(roots stringList, disabled bool, k instance.Kind) error {
	seen := make(map[string]bool, len(roots))
	for _, root := range roots {
		clean := filepath.Clean(root)
		if seen[clean] {
			return fmt.Errorf("duplicate --root %s", root)
		}
		seen[clean] = true
	}
	if disabled || k != instance.KindInstance {
		return nil
	}
	for _, root := range roots {
		info, err := os.Stat(root)
		if err != nil {
			if errors.Is(err, fs.ErrNotExist) {
				return fmt.Errorf("root %s does not exist (store it with --kind backup-copy or --disabled to skip the check)", root)
			}
			return fmt.Errorf("root %s: %w", root, err)
		}
		if !info.IsDir() {
			return fmt.Errorf("root %s is not a directory", root)
		}
	}
	return nil
}

func sourceEntryByID(cfg *instance.Config, id string) (instance.Entry, bool) {
	for _, e := range cfg.Entries {
		if e.ID == id {
			return e, true
		}
	}
	return instance.Entry{}, false
}

func printSourceEntry(out, errout io.Writer, js bool, verb string, e instance.Entry) int {
	if js {
		if err := json.NewEncoder(out).Encode(e); err != nil {
			fmt.Fprintln(errout, err)
			return 1
		}
		return 0
	}
	fmt.Fprintf(out, "%s instance %s (harness %s, kind %s)\n", verb, e.ID, e.Harness, e.Kind)
	if e.Label != "" {
		fmt.Fprintf(out, "  label %s\n", e.Label)
	}
	if e.Disabled {
		fmt.Fprintln(out, "  disabled")
	}
	for _, root := range e.Roots {
		fmt.Fprintf(out, "  root %s\n", root)
	}
	return 0
}

func reportSourcesError(errout io.Writer, cmd string, err error) int {
	var ce *instance.ConfigError
	if errors.As(err, &ce) {
		fmt.Fprintf(errout, "%s: %s\n", cmd, ce.Error())
	} else {
		fmt.Fprintf(errout, "%s: %v\n", cmd, err)
	}
	return 1
}
