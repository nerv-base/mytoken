// sourceFallbacks lists the parsers' own default roots. It is a package
// variable only so tests can substitute temp roots instead of reading the real
// home directory; production always asks the registered parsers.
var sourceFallbacks = instance.DefaultFallbacks

const sourcesUsage = `Usage: mytoken sources <subcommand> [options]
  sources list [--json]
  sources add --harness NAME --root PATH [--root PATH ...] [--id ID] [--label TEXT]
              [--kind instance|backup-copy] [--disabled] [--json]
  sources move <id> --root PATH [--root PATH ...] [--json]
  sources remove <id> [--json]
  sources promote <id> [--json]

sources reads and edits sources.json in the data directory: the shared instance
configuration every reader of the index agrees on. It never refreshes prices and
never reads a log file. list is read-only and does not create the data
directory; when the index exists it is opened read-only to show, per harness
instance, what the scanner last attempted and last found (attempt and success
times, discovered files, new events, indexed sessions and the scanner's own
reason), and never as a zero when no record was stored at all. A disabled or
backup-copy entry is never scanned and keeps its configuration status.

--root is repeatable. An enabled instance must name at least one existing,
readable directory, and a bad path is rejected here instead of being stored and
discovered later. A backup-copy entry, or one stored with --disabled, keeps its
roots verbatim and is never scanned, counted or stat'ed.

ids are opaque and generated by add (or supplied with --id); move and promote
keep the id, because the id is the instance's identity in the index. promote is
the only way a backup-copy becomes scannable. remove deletes the configuration
entry only: no database, cursor, log or directory is ever deleted.
Exit status: 0 success, 1 operational error, 2 invalid arguments.
`

// Per-subcommand usage lines, printed on a usage error. They all start with
// "Usage: mytoken sources" so a caller can grep one prefix for every mistake.
const (
	sourcesListUsage    = "Usage: mytoken sources list [--json]\n"
	sourcesAddUsage     = "Usage: mytoken sources add --harness NAME --root PATH [--root PATH ...] [--id ID] [--label TEXT] [--kind instance|backup-copy] [--disabled] [--json]\n"
	sourcesMoveUsage    = "Usage: mytoken sources move <id> --root PATH [--root PATH ...] [--json]\n"
	sourcesRemoveUsage  = "Usage: mytoken sources remove <id> [--json]\n"
	sourcesPromoteUsage = "Usage: mytoken sources promote <id> [--json]\n"
)

// sourceRoot is one configured root and whether it is usable right now.
type sourceRoot struct {
	Path   string `json:"path"`
	Exists bool   `json:"exists"`
}

// sourceEntry is one resolved data source: configured instances first, then the
// parsers' own defaults.
type sourceEntry struct {
	ID        string       `json:"id"`
	Label     string       `json:"label,omitempty"`
	Harness   string       `json:"harness"`
	Kind      string       `json:"kind"`
	Origin    string       `json:"origin"`
	Status    string       `json:"status"`
	Scannable bool         `json:"scannable"`
	Roots     []sourceRoot `json:"roots"`
	Reason    string       `json:"reason,omitempty"`
	// Diagnostics is what the index actually recorded for this harness
	// instance: when a scan last attempted it, when it last succeeded, what it
	// found and why. It is always present, and unavailable with a reason when
	// there is no applicable record, so a missing record is never read as a
	// zero count. Disabled and backup-copy entries are never scanned and report
	// not_collected while keeping their configuration status.
	Diagnostics snapshot.InstanceDiagnostics `json:"diagnostics"`
}

// sourceProblem is one diagnostic reason, fatal or not.
type sourceProblem struct {
	Code    string `json:"code"`
	ID      string `json:"id,omitempty"`
	Harness string `json:"harness,omitempty"`
	Path    string `json:"path,omitempty"`
	Message string `json:"message"`
	Fatal   bool   `json:"fatal"`
}

// sourceReport is the text/JSON diagnostics surface shared by "sources list"
// and "doctor". It carries paths, never credentials, and never reads a log.
type sourceReport struct {
	ConfigPath    string          `json:"configPath"`
	ConfigPresent bool            `json:"configPresent"`
	ConfigError   string          `json:"configError,omitempty"`
	Instances     []sourceEntry   `json:"instances"`
	Problems      []sourceProblem `json:"problems"`
}

// buildSourceReport resolves the shared config plus the parsers' defaults into
// the diagnostic report. It never writes anything.
func buildSourceReport(dataDir string, fallbacks []instance.Fallback) sourceReport {
	path := filepath.Join(dataDir, instance.FileName)
	rep := sourceReport{ConfigPath: path, Instances: []sourceEntry{}, Problems: []sourceProblem{}}
	if _, err := os.Stat(path); err == nil {
		rep.ConfigPresent = true
	}
	cfg, err := instance.Load(dataDir)
	if err != nil {
		rep.ConfigError = err.Error()
		code := string(instance.CodeInvalidConfig)
		var ce *instance.ConfigError
		if errors.As(err, &ce) {
			code = string(ce.Code)
		}
		rep.Problems = append(rep.Problems, sourceProblem{Code: code, Path: path, Message: err.Error(), Fatal: true})
		return rep
	}
	resolved, problems := instance.Resolve(cfg, fallbacks)
	fatalReason := map[string]string{}
	softReason := map[string]string{}
	for _, p := range problems {
		rep.Problems = append(rep.Problems, sourceProblem{
			Code: string(p.Code), ID: p.ID, Harness: string(p.Harness),
			Path: p.Path, Message: p.Message, Fatal: p.Fatal,
		})
		key := sourceKey(p.Harness, p.ID)
		if p.Fatal {
			if _, ok := fatalReason[key]; !ok {
				fatalReason[key] = p.Message
			}
			continue
		}
		if _, ok := softReason[key]; !ok {
			softReason[key] = p.Message
		}
	}
	for _, r := range resolved {
		key := sourceKey(r.Harness, r.ID)
		entry := sourceEntry{
			ID: r.ID, Label: r.Label, Harness: string(r.Harness),
			Kind: string(r.Kind), Origin: string(r.Source), Roots: []sourceRoot{},
		}
		seen := make(map[string]bool, len(r.Roots)+1)
		for _, root := range r.Roots {
			_, statErr := os.Stat(root)
			entry.Roots = append(entry.Roots, sourceRoot{Path: root, Exists: statErr == nil})
			seen[root] = true
		}
		// A root that resolve refused is not in Roots; show it as missing so the
		// diagnostic names the path the user has to fix.
		for _, p := range problems {
			if sourceKey(p.Harness, p.ID) != key || p.Path == "" || seen[p.Path] {
				continue
			}
			entry.Roots = append(entry.Roots, sourceRoot{Path: p.Path, Exists: false})
			seen[p.Path] = true
		}
		switch {
		case r.Disabled:
			entry.Status = "disabled"
		case r.Kind == instance.KindBackupCopy:
			entry.Status = "backup-copy"
		case fatalReason[key] != "":
			entry.Status = "error"
		default:
			entry.Status = "enabled"
		}
		entry.Scannable = r.Scannable() && fatalReason[key] == ""
		if msg := softReason[key]; msg != "" {
			entry.Reason = msg
		} else {
			entry.Reason = fatalReason[key]
		}
		rep.Instances = append(rep.Instances, entry)
	}
	return rep
}

func sourceKey(h model.Harness, id string) string { return string(h) + "\x00" + id }

// presentWord renders a file-state flag for the text views.
func presentWord(present bool) string {
	if present {
		return "present"
	}
	return "absent"
}

// sourceReportFailed reports whether the report describes a config that cannot
// be scanned: an unreadable config, or any fatal problem.
func sourceReportFailed(rep sourceReport) bool {
	if rep.ConfigError != "" {
		return true
	}
	for _, p := range rep.Problems {
		if p.Fatal {
			return true
		}
	}
	return false
}

func writeSourceReport(out io.Writer, rep sourceReport) error {
	fmt.Fprintf(out, "Config: %s (%s)\n", rep.ConfigPath, presentWord(rep.ConfigPresent))
	if rep.ConfigError != "" {
		fmt.Fprintf(out, "  error: %s\n", rep.ConfigError)
	}
	w := newTable(out)
	fmt.Fprintln(w, "ID\tHARNESS\tORIGIN\tKIND\tSTATUS\tSCANNABLE\tROOTS\tREASON\tDIAGNOSTICS")
	for _, e := range rep.Instances {
		roots := make([]string, 0, len(e.Roots))
		for _, r := range e.Roots {
			label := r.Path
			if !r.Exists {
				label += " (missing)"
			}
			roots = append(roots, label)
		}
		fmt.Fprintf(w, "%s\t%s\t%s\t%s\t%s\t%t\t%s\t%s\t%s\n", e.ID, e.Harness, e.Origin, e.Kind, e.Status, e.Scannable, strings.Join(roots, ","), e.Reason, diagnosticsCell(e.Diagnostics))
	}
	if err := w.Flush(); err != nil {
		return err
	}
	// The evidence under the table: one block per instance, including the
	// source paths the scan itself reported. Printed after the table flush so
	// the column writer never reflows these lines.
	if len(rep.Instances) > 0 {
		writeDiagnosticsDetail(out, rep.Instances)
	}
	if len(rep.Problems) > 0 {
		pw := newTable(out)
		fmt.Fprintln(pw, "PROBLEMS")
		for _, p := range rep.Problems {
			severity := "warning"
			if p.Fatal {
				severity = "fatal"
			}
			fmt.Fprintf(pw, "%s\t%s\t%s\t%s\t%s\n", severity, p.Code, p.Harness, p.Path, p.Message)
		}
		return pw.Flush()
	}
	return nil
}

// runSources is `mytoken sources`: diagnostics plus the config edits. It never
// touches a configured directory and never writes the index; list opens the
// index read-only to show the collection evidence a scan recorded.
func runSources(ctx context.Context, args []string, out, errout io.Writer) int {
	if len(args) == 0 {
		fmt.Fprint(errout, sourcesUsage)
		return 2
	}
	switch args[0] {
	case "list":
		return runSourcesList(ctx, args[1:], out, errout)
	case "add":
		return runSourcesAdd(args[1:], out, errout)
	case "move":
		return runSourcesMove(args[1:], out, errout)
	case "remove":
		return runSourcesRemove(args[1:], out, errout)
	case "promote":
		return runSourcesPromote(args[1:], out, errout)
	default:
		fmt.Fprintln(errout, "unknown sources subcommand:", args[0])
		fmt.Fprint(errout, sourcesUsage)
		return 2
	}
}

func runSourcesList(ctx context.Context, args []string, out, errout io.Writer) int {
	fs := flag.NewFlagSet("sources list", flag.ContinueOnError)
	fs.SetOutput(errout)
	js := fs.Bool("json", false, "JSON output")
	if err := fs.Parse(args); err != nil {
		return 2
	}
	if fs.NArg() != 0 {
		fmt.Fprint(errout, sourcesListUsage)
		return 2
	}
	dir, err := paths.ResolveDataDir()
	if err != nil {
		fmt.Fprintln(errout, err)
		return 1
	}
	rep := buildSourceReport(dir, sourceFallbacks())
	// The evidence next to the configuration: which instances a scan actually
	// reached, from the index, read-only. It never changes the config status.
	attachSourceDiagnostics(ctx, &rep, nil, nil)
	if *js {
		err = json.NewEncoder(out).Encode(rep)
	} else {
		err = writeSourceReport(out, rep)
	}
	if err != nil {
		fmt.Fprintln(errout, err)
		return 1
	}
	if sourceReportFailed(rep) {
		if rep.ConfigError != "" {
			fmt.Fprintln(errout, rep.ConfigError)
		} else {
			for _, p := range rep.Problems {
				if p.Fatal {
					fmt.Fprintf(errout, "sources: %s: %s\n", p.Code, p.Message)
					break
				}
			}
		}
		return 1
	}
	return 0
}

func runSourcesAdd(args []string, out, errout io.Writer) int {
	fs := flag.NewFlagSet("sources add", flag.ContinueOnError)
	fs.SetOutput(errout)
	js := fs.Bool("json", false, "JSON output")
	disabled := fs.Bool("disabled", false, "store the entry disabled (never scanned)")
	harnessFlag := fs.String("harness", "", "harness that writes the logs (required)")
	id := fs.String("id", "", "explicit instance id (default: a generated opaque id)")
	label := fs.String("label", "", "human label (display only)")
	kind := fs.String("kind", string(instance.KindInstance), "instance or backup-copy")
	var roots stringList
	fs.Var(&roots, "root", "log root directory (repeatable)")
	flags, positional, e := splitArgs(args, map[string]bool{"json": true, "disabled": true})
	if e != nil {
		fmt.Fprintln(errout, e)
		return 2
	}
	if e := fs.Parse(flags); e != nil {
		return 2
	}
	if len(positional) != 0 {
		fmt.Fprint(errout, sourcesAddUsage)
		return 2
	}
	h := model.Harness(strings.TrimSpace(*harnessFlag))
	if h == "" || !knownHarness(string(h)) {
		// A missing --harness and a misspelled one are the same mistake to fix,
		// and both are reported as an unknown harness so scripts can match one
		// phrase; the missing case also says the flag is required.
		if h == "" {
			fmt.Fprintln(errout, `sources add: unknown harness "" (--harness is required; want a harness id such as claude-code, codex or dsh)`)
		} else {
			fmt.Fprintf(errout, "sources add: unknown harness %q (want a harness id such as claude-code, codex or dsh)\n", h)
		}
		fmt.Fprint(errout, sourcesAddUsage)
		return 2
	}
	k, e := parseKind(*kind)
	if e != nil {
		fmt.Fprintln(errout, "sources add:", e)
		return 2
	}
	if len(roots) == 0 {
		fmt.Fprintln(errout, "sources add: at least one --root is required")
		return 2
	}
	if e := checkRoots(roots, *disabled, k); e != nil {
		fmt.Fprintln(errout, "sources add:", e)
		return 2
	}
	dir, err := paths.ResolveDataDir()
	if err != nil {
		fmt.Fprintln(errout, err)
		return 1
	}
	req := instance.AddRequest{
		ID: strings.TrimSpace(*id), Label: *label, Harness: h,
		Roots: roots.values(), Kind: k, Disabled: *disabled,
	}
	var entry instance.Entry
	if _, err = instance.Update(dir, func(c *instance.Config) error {
		var addErr error
		entry, addErr = c.Add(req)
		return addErr
	}); err != nil {
		return reportSourcesError(errout, "sources add", err)
	}
	return printSourceEntry(out, errout, *js, "Added", entry)
}

func runSourcesMove(args []string, out, errout io.Writer) int {
	fs := flag.NewFlagSet("sources move", flag.ContinueOnError)
	fs.SetOutput(errout)
	js := fs.Bool("json", false, "JSON output")
	var roots stringList
	fs.Var(&roots, "root", "log root directory (repeatable)")
	flags, positional, e := splitArgs(args, map[string]bool{"json": true})
	if e != nil {
		fmt.Fprintln(errout, e)
		return 2
	}
	if e := fs.Parse(flags); e != nil {
		return 2
	}
	if len(positional) != 1 {
		fmt.Fprint(errout, sourcesMoveUsage)
		return 2
	}
	if len(roots) == 0 {
		fmt.Fprintln(errout, "sources move: at least one --root is required")
		return 2
	}
	id := positional[0]
	dir, err := paths.ResolveDataDir()
	if err != nil {
		fmt.Fprintln(errout, err)
		return 1
	}
	// Root checking depends on the entry's current kind, so read it first. A
	// read failure is left to Update, which refuses to overwrite the file.
	if cfg, loadErr := instance.Load(dir); loadErr == nil {
		if cur, ok := sourceEntryByID(cfg, id); ok && !cur.Disabled && cur.Kind == instance.KindInstance {
			if e := checkRoots(roots, false, instance.KindInstance); e != nil {
				fmt.Fprintln(errout, "sources move:", e)
				return 2
			}
		}
	}
	var entry instance.Entry
	if _, err = instance.Update(dir, func(c *instance.Config) error {
		var moveErr error
		entry, moveErr = c.Move(id, roots.values())
		return moveErr
	}); err != nil {
		return reportSourcesError(errout, "sources move", err)
	}
	return printSourceEntry(out, errout, *js, "Moved", entry)
}

func runSourcesRemove(args []string, out, errout io.Writer) int {
	fs := flag.NewFlagSet("sources remove", flag.ContinueOnError)
	fs.SetOutput(errout)
	js := fs.Bool("json", false, "JSON output")
	flags, positional, e := splitArgs(args, map[string]bool{"json": true})
	if e != nil {
		fmt.Fprintln(errout, e)
		return 2
	}
	if e := fs.Parse(flags); e != nil {
		return 2
	}
	if len(positional) != 1 {
		fmt.Fprint(errout, sourcesRemoveUsage)
		return 2
	}
	id := positional[0]
	dir, err := paths.ResolveDataDir()
	if err != nil {
		fmt.Fprintln(errout, err)
		return 1
	}
	if _, err = instance.Update(dir, func(c *instance.Config) error { return c.Remove(id) }); err != nil {
		return reportSourcesError(errout, "sources remove", err)
	}
	if *js {
		if err = json.NewEncoder(out).Encode(struct {
			ID      string `json:"id"`
			Removed bool   `json:"removed"`
		}{ID: id, Removed: true}); err != nil {
			fmt.Fprintln(errout, err)
			return 1
		}
		return 0
	}
	fmt.Fprintf(out, "Removed instance %s (configuration entry only; no data was deleted)\n", id)
	return 0
}

